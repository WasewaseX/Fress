"""CLI-level contract tests for scripts/ci/validate-versions.ts.

The TypeScript suite (src/lib/__tests__/versionCoherence.test.ts) covers the
validator's rules in depth; this file pins the STABLE-RELEASE invocation
contract at the process boundary, the same way release.yml and a human
release driver experience it:

  - tag v1.0.0 passes release mode on a coherent stable fixture, and a
    v1.0.1 tag is rejected on the very same fixture (mismatch, exit 1);
  - a stable candidate at 1.0.0 is legal in development mode while
    v1.0.12-beta is the newest published release: the validator is offline,
    never consults release history, and never claims 1.0.0 is numerically
    older/newer than the beta line (the stable-track inversion is legal);
  - a partial bump (one field left at 1.0.12-beta) fails closed, naming
    file, field and both values;
  - --is-prerelease classifies 1.0.0 as stable (prints "false"),
    1.0.0-beta.1 / 1.0.13-beta as prerelease (prints "true"), and an
    unparsable version fails CLOSED with exit 2 (never classified stable);
  - an unparsable --release-tag is a validation failure (exit 1), distinct
    from the usage error exit 2;
  - the REAL checkout in this repository passes default mode.

No git tag is ever created: every release scenario runs against a synthetic
fixture root under tempfile.mkdtemp() passed via --root.

The validator is invoked with plain `node`: Node >= 23.6 strips TypeScript
types natively, so no npm install / tsx dependency is needed. That keeps
this suite hermetic for the artifact-audit-tests CI job, which installs no
node_modules (unittest discover -s scripts/ci -p 'test_*.py').

Run:  python3 -m unittest discover -s scripts/ci -p 'test_*.py' -v
"""
import json
import os
import re
import shutil
import subprocess
import tempfile
import unittest

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.abspath(os.path.join(_HERE, "..", ".."))
_VALIDATOR = os.path.join(_HERE, "validate-versions.ts")

# Native TS type stripping: unflagged from Node 23.6, --experimental-strip-types
# from 22.7. Older nodes cannot run the validator directly; the repo itself
# requires a modern node anyway, so skipping there is honest, not silent.
_NODE = shutil.which("node")


def _node_runtime():
    if _NODE is None:
        return None
    try:
        out = subprocess.run(
            [_NODE, "--version"], capture_output=True, text=True, timeout=30
        ).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return None
    m = re.match(r"v(\d+)\.(\d+)", out)
    if not m:
        return None
    major, minor = int(m.group(1)), int(m.group(2))
    if major >= 24 or (major == 23 and minor >= 6):
        return [_NODE]
    if (major == 23) or (major == 22 and minor >= 7):
        return [_NODE, "--experimental-strip-types"]
    return None


_RUNTIME = _node_runtime()


def _run_validator(args):
    return subprocess.run(
        _RUNTIME + [_VALIDATOR] + args,
        capture_output=True,
        text=True,
        timeout=120,
    )


def _write_stable_fixture(root: str) -> None:
    """A coherent 1.0.0 checkout: the six authoritative fields, nothing else.
    The optional-authoritative files (generated Android project, plugin
    crate) are absent, which is their legitimate pre-generation state."""
    files = {
        "package.json": {"name": "fress", "version": "1.0.0", "private": True},
        "package-lock.json": {
            "name": "fress",
            "version": "1.0.0",
            "lockfileVersion": 3,
            "packages": {"": {"name": "fress", "version": "1.0.0"}},
        },
        "src-tauri/Cargo.toml": '[package]\nname = "fress"\nversion = "1.0.0"\n',
        "src-tauri/Cargo.lock": (
            "# This file is automatically @generated by Cargo.\n"
            "version = 4\n\n"
            '[[package]]\nname = "fress"\nversion = "1.0.0"\n'
        ),
        "src-tauri/tauri.conf.json": {
            "$schema": "https://schema.tauri.app/config/2",
            "productName": "Fress",
            "version": "1.0.0",
        },
    }
    for rel, content in files.items():
        abs_path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(abs_path), exist_ok=True)
        if isinstance(content, str):
            with open(abs_path, "w", encoding="utf-8") as fh:
                fh.write(content)
        else:
            with open(abs_path, "w", encoding="utf-8") as fh:
                json.dump(content, fh, indent=2)
                fh.write("\n")


@unittest.skipUnless(_RUNTIME, "node >= 22.7 with native TS type stripping is required")
class TestStableTrackReleaseMode(unittest.TestCase):
    """Release mode binds the tag to the build version - on the stable track
    exactly like on the beta track."""

    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="fress-version-fixture-")
        self.addCleanup(shutil.rmtree, self.root, ignore_errors=True)
        _write_stable_fixture(self.root)

    def test_v1_0_0_tag_passes_release_mode(self):
        run = _run_validator(["--release-tag", "v1.0.0", "--root", self.root])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertIn("validate:versions PASSED", run.stdout)
        self.assertIn("with release tag v1.0.0", run.stdout)
        # All six fields plus the tag row agree.
        self.assertEqual(run.stdout.count(" ok"), 6, run.stdout)

    def test_v1_0_1_tag_mismatch_is_rejected(self):
        run = _run_validator(["--release-tag", "v1.0.1", "--root", self.root])
        self.assertEqual(run.returncode, 1, run.stdout + run.stderr)
        self.assertIn("validate:versions FAILED", run.stdout)
        self.assertIn("disagrees with the build version", run.stdout)
        self.assertIn("1.0.1", run.stdout)
        self.assertIn("1.0.0", run.stdout)
        self.assertIn("NEVER move or retarget an already-published tag", run.stdout)

    def test_unparsable_tag_is_a_validation_failure_not_a_usage_error(self):
        run = _run_validator(["--release-tag", "v1.0.0junk", "--root", self.root])
        self.assertEqual(run.returncode, 1, run.stdout + run.stderr)
        self.assertIn('is not a valid project version tag', run.stdout)

    def test_partial_bump_left_in_tauri_conf_fails_closed(self):
        conf_path = os.path.join(self.root, "src-tauri", "tauri.conf.json")
        with open(conf_path, encoding="utf-8") as fh:
            conf = json.load(fh)
        conf["version"] = "1.0.12-beta"  # one field missed the stable bump
        with open(conf_path, "w", encoding="utf-8") as fh:
            json.dump(conf, fh, indent=2)
            fh.write("\n")
        run = _run_validator(["--release-tag", "v1.0.0", "--root", self.root])
        self.assertEqual(run.returncode, 1, run.stdout + run.stderr)
        self.assertIn("src-tauri/tauri.conf.json .version", run.stdout)
        self.assertIn('"1.0.12-beta"', run.stdout)
        self.assertIn('"1.0.0"', run.stdout)

    def test_stable_candidate_is_legal_in_dev_mode_while_v1_0_12_beta_is_published(self):
        # No --release-tag => development mode. The validator is offline and
        # must never compare against published release history: a tree at
        # 1.0.0 while v1.0.12-beta is the newest published release is the
        # legitimate stable-candidate state (the SemVer inversion 1.0.0 <
        # 1.0.12-beta must NOT reject it).
        run = _run_validator(["--root", self.root])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertIn("validate:versions PASSED", run.stdout)
        self.assertIn("release-tag mode: off", run.stdout)
        self.assertIn("the development version may differ", run.stdout)


@unittest.skipUnless(_RUNTIME, "node >= 22.7 with native TS type stripping is required")
class TestIsPrereleaseClassification(unittest.TestCase):
    """The one authoritative stable/prerelease classification release.yml
    consumes for the GitHub prerelease flag."""

    def test_plain_1_0_0_is_stable(self):
        run = _run_validator(["--is-prerelease", "1.0.0"])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(run.stdout.strip(), "false")

    def test_v1_0_0_is_stable(self):
        run = _run_validator(["--is-prerelease", "v1.0.0"])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(run.stdout.strip(), "false")

    def test_1_0_0_beta_1_is_prerelease(self):
        run = _run_validator(["--is-prerelease", "1.0.0-beta.1"])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(run.stdout.strip(), "true")

    def test_1_0_13_beta_is_prerelease(self):
        # The legitimate post-stable-release beta: still prerelease wording,
        # never shipped as a stable GitHub release.
        run = _run_validator(["--is-prerelease", "1.0.13-beta"])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertEqual(run.stdout.strip(), "true")

    def test_garbage_fails_closed(self):
        run = _run_validator(["--is-prerelease", "garbage"])
        self.assertEqual(run.returncode, 2, run.stdout + run.stderr)
        self.assertIn("is not a valid project version", run.stderr)
        self.assertIn("never classified as stable", run.stderr)


@unittest.skipUnless(_RUNTIME, "node >= 22.7 with native TS type stripping is required")
class TestRealCandidateTree(unittest.TestCase):
    """The actual checkout this suite ships with must pass default mode:
    if the release candidate drifts (partial bump, malformed manifest),
    the ordinary CI gate fails here too."""

    def test_real_checkout_passes_default_mode(self):
        run = _run_validator([])
        self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
        self.assertIn("validate:versions PASSED", run.stdout)
        # One source row + five agreeing fields.
        self.assertEqual(run.stdout.count(" ok"), 5, run.stdout)


if __name__ == "__main__":
    unittest.main()
