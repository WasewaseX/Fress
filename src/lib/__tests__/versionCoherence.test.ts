describe('optional Android parsers', () => {
  it('parseGradleKtsVersionName: Kotlin DSL assignment, Groovy style, and comment immunity', () => {
    expect(parseGradleKtsVersionName(androidGradleKts('1.0.10-beta'))).toEqual({ kind: 'ok', value: '1.0.10-beta' });
    expect(parseGradleKtsVersionName(androidGradleKts('1.0.10-beta', { groovyStyle: true }))).toEqual({ kind: 'ok', value: '1.0.10-beta' });
    // A commented-out historical assignment must never be read as the version.
    expect(parseGradleKtsVersionName(androidGradleKts('1.0.10-beta', { extraCommentLine: true }))).toEqual({ kind: 'ok', value: '1.0.10-beta' });
    expect(parseGradleKtsVersionName('// versionName = "9.9.9-old"\nversionName = "1.0.10-beta" // live')).toEqual({ kind: 'ok', value: '1.0.10-beta' });
  });

  it('parseGradleKtsVersionName: zero, ambiguous and unquoted assignments fail closed', () => {
    expectErr(parseGradleKtsVersionName('android {\n  defaultConfig {\n    applicationId = "x"\n  }\n}'), 'no parseable versionName');
    expectErr(
      parseGradleKtsVersionName('versionName = "1.0.10-beta"\nversionName = "1.0.9-beta"'),
      '2 versionName assignments'
    );
    // Unquoted Kotlin property (versionName from a variable) is not a literal
    // the build pins — treated as missing, not guessed.
    expectErr(parseGradleKtsVersionName('versionName = project.findProperty("v") as String'), 'no parseable versionName');
  });

  it('parseGradleKtsVersionName: the Tauri CLI 2.11+ delegation shape resolves from tauri.properties', () => {
    // The exact line the current CLI generates (Kotlin DSL, default kept in
    // the getProperty call — the default is NOT authoritative).
    const generated = '    versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")';
    expect(parseGradleKtsVersionName(generated)).toEqual({ kind: 'delegated' });
    // Groovy-ish double-quoted property key and no default are also delegation.
    expect(parseGradleKtsVersionName('versionName = tauriProperties.getProperty("tauri.android.versionName")')).toEqual({ kind: 'delegated' });
    // A commented delegation is not one.
    expectErr(parseGradleKtsVersionName('// versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")'), 'no parseable versionName');
    // A literal MIXED with a delegation is ambiguous — which one does the build use?
    expectErr(
      parseGradleKtsVersionName('versionName = "1.0.10-beta"\nversionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")'),
      'ambiguous'
    );
    // Two delegations are ambiguous too.
    expectErr(
      parseGradleKtsVersionName(
        'versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")\nversionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")'
      ),
      'ambiguous'
    );
  });

  it('parseTauriPropertiesVersionName: the generated properties file parses, and junk fails closed', () => {
    const generated = [
      '// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
      'tauri.android.versionName=1.0.10-beta',
      'tauri.android.versionCode=1000010',
    ].join('\n');
    expect(parseTauriPropertiesVersionName(generated)).toEqual({ kind: 'ok', value: '1.0.10-beta' });
    // Comments and surrounding whitespace are ignored.
    expect(parseTauriPropertiesVersionName('# why\n  turi.placeholder=1\n\ntauri.android.versionName = 1.0.10-beta  ')).toEqual({
      kind: 'ok',
      value: '1.0.10-beta',
    });
    // Absent entry, duplicates and an empty value fail closed.
    expectErr(parseTauriPropertiesVersionName('tauri.android.versionCode=1'), 'no parseable tauri.android.versionName');
    expectErr(
      parseTauriPropertiesVersionName('tauri.android.versionName=1.0.10-beta\ntauri.android.versionName=1.0.9-beta'),
      '2 tauri.android.versionName entries'
    );
    expectErr(parseTauriPropertiesVersionName('tauri.android.versionName='), 'empty tauri.android.versionName');
  });

  it('validateVersions: a delegating build.gradle.kts is verified through its tauri.properties', () => {
    const gradle = [
      'import java.util.Properties',
      'val tauriProperties = Properties().apply {',
      '    val propFile = file("tauri.properties")',
      '}',
      'android {',
      '    defaultConfig {',
      '        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")',
      '    }',
      '}',
    ].join('\n');
    // Delegation + agreeing properties -> passes (a new authoritative row).
    const pass = validate(coherentFiles(), {
      optionalFiles: {
        [GRADLE_PATH]: gradle,
        'src-tauri/gen/android/app/tauri.properties': 'tauri.android.versionName=1.0.10-beta\ntauri.android.versionCode=1000010',
      },
    });
    expect(pass.ok).toBe(true);
    expect(pass.checks).toContainEqual(expect.objectContaining({ file: 'src-tauri/gen/android/app/tauri.properties', field: 'tauri.android.versionName', status: 'ok' }));

    // Delegation + MISSING properties -> fail closed (cannot verify).
    const missing = validate(coherentFiles(), { optionalFiles: { [GRADLE_PATH]: gradle } });
    expect(missing.ok).toBe(false);
    expect(failureText(missing)).toContain('delegates versionName');
    expect(failureText(missing)).toContain('tauri.properties');

    // Delegation + DISAGREEING properties -> drift, named with both values.
    const stale = validate(coherentFiles(), {
      optionalFiles: {
        [GRADLE_PATH]: gradle,
        'src-tauri/gen/android/app/tauri.properties': 'tauri.android.versionName=1.0.9-beta',
      },
    });
    expect(stale.ok).toBe(false);
    expect(failureText(stale)).toContain('"1.0.9-beta"');
    expect(failureText(stale)).toContain('expected "1.0.10-beta"');
  });

  it('parseTauriAndroidVersionName: absent path, present override, and malformed values', () => {
    // No bundle section at all (the current repo state).
    expect(parseTauriAndroidVersionName(JSON.stringify({ productName: 'Fress', version: '1.0.10-beta' }))).toEqual({ kind: 'absent' });
    // bundle exists without android, android without versionName.
    expect(parseTauriAndroidVersionName(JSON.stringify({ bundle: { targets: ['nsis'] } }))).toEqual({ kind: 'absent' });
    expect(parseTauriAndroidVersionName(JSON.stringify({ bundle: { android: {} } }))).toEqual({ kind: 'absent' });
    // A real override.
    expect(parseTauriAndroidVersionName(JSON.stringify({ bundle: { android: { versionName: '1.0.10-beta' } } }))).toEqual({ kind: 'ok', value: '1.0.10-beta' });
    // Present-but-malformed never silently passes.
    expectOptionalErr(parseTauriAndroidVersionName(JSON.stringify({ bundle: { android: { versionName: 42 } } })), 'not a non-empty string');
    expectOptionalErr(parseTauriAndroidVersionName(JSON.stringify({ bundle: { android: { versionName: '' } } })), 'not a non-empty string');
  });
});

