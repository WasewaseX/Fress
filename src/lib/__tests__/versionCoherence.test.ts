/**
 * Regression coverage for scripts/ci/validate-versions.ts
 * (`npm run validate:versions`).
 *
 * The validator's core is pure: it takes file CONTENT by path, so every rule
 * below runs against in-memory fixtures — no production file is ever mutated
 * to manufacture a failure state. The two spawn tests at the end exercise the
 * real npm script (the stable interface Agent 4 wires into CI) for actual
 * exit codes.
 */

import { mkdtempSync, rmSync, writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { afterAll, describe, expect, it } from 'vitest';

import {
  loadVersionFiles,
  parseCargoLockFressVersion,
  parseCargoTomlVersion,
  stripVPrefix,
  validateVersions,
  type ParseResult,
  type RequiredFile,
  type ValidateInput,
} from '../../../scripts/ci/validate-versions';

/** Assert a parser result is the expected failure (explicit narrowing, no
 * union gymnastics at the call site). */
function expectErr(result: ParseResult, fragment: string): void {
  if (result.kind === 'ok') {
    throw new Error(`expected a failure containing "${fragment}", got ok with value "${result.value}"`);
  }
  expect(result.error).toContain(fragment);
}

// -- fixtures -----------------------------------------------------------------

/** A fully coherent candidate: every authoritative field says 1.0.10-beta. */
function coherentFiles(version = '1.0.10-beta'): Partial<Record<RequiredFile, string>> {
  return {
    'package.json': JSON.stringify({ name: 'fress', version }, null, 2),
    'package-lock.json': JSON.stringify(
      { name: 'fress', version, lockfileVersion: 3, packages: { '': { name: 'fress', version } } },
      null,
      2
    ),
    'src-tauri/Cargo.toml': [
      '[package]',
      `name = "fress"`,
      `version = "${version}"`,
      'edition = "2021"',
      '',
      '[lib]',
      'name = "fress_lib"',
      '',
      '[dependencies]',
      'serde = { version = "1", features = ["derive"] }',
    ].join('\n'),
    'src-tauri/Cargo.lock': [
      '# This file is automatically @generated by Cargo.',
      '# It is not intended for manual editing.',
      'version = 4',
      '',
      '[[package]]',
      'name = "serde"',
      'version = "1.0.219"',
      '',
      '[[package]]',
      'name = "fress"',
      `version = "${version}"`,
      'dependencies = [',
      ' "serde",',
      ']',
    ].join('\n'),
    'src-tauri/tauri.conf.json': JSON.stringify(
      { $schema: 'https://schema.tauri.app/config/2', productName: 'Fress', version, app: { security: {} } },
      null,
      2
    ),
  };
}

/** Historical changelog text: PAST versions are supposed to appear here and
 * must never influence the check. */
const HISTORICAL_CHANGELOG = [
  '# Changelog',
  '',
  '## 1.0.10-beta (2026-10-12): the contrast-acceptance release',
  '- shipped things',
  '',
  '## 1.0.9-beta (2026-10-12): the verified-delivery release',
  '- older things',
  '',
  '## 1.0.8-beta (2026-10-02)',
  '- even older things',
].join('\n');

function validate(files: Partial<Record<RequiredFile, string>>, rest: Omit<ValidateInput, 'files'> = {}) {
  return validateVersions({ files, ...rest });
}

const failureText = (r: { failures: string[] }) => r.failures.join('\n');

// -- parser edge contracts ----------------------------------------------------

describe('Cargo parsers', () => {
  it('Cargo.toml: [package] version survives comments, inline comments and surrounding tables', () => {
    const text = [
      '# a full-line comment mentioning version = "9.9.9-junk"',
      '[package]',
      'name = "fress"',
      'version = "1.0.10-beta" # inline comment',
      '',
      '[package.metadata.notes]',
      'version = "this is prose, not the version"',
      '',
      '[dependencies]',
      'serde = { version = "1" }',
    ].join('\n');
    expect(parseCargoTomlVersion(text)).toEqual({ kind: 'ok', value: '1.0.10-beta' });
  });

  it('Cargo.toml: a [package.metadata] version is never mistaken for the package version', () => {
    const text = ['[package.metadata]', 'version = "0.0.0-wrong"', '[package]', 'version = "1.0.10-beta"'].join('\n');
    expect(parseCargoTomlVersion(text)).toEqual({ kind: 'ok', value: '1.0.10-beta' });
  });

  it('Cargo.toml: missing [package] table and missing version key fail with specific errors', () => {
    expectErr(parseCargoTomlVersion('[lib]\nname = "x"'), 'no [package] table');
    expectErr(parseCargoTomlVersion('[package]\nname = "fress"'), '[package] has no "version" key');
  });

  it('Cargo.lock: the fress entry is found among many; the lockfile-format version = 4 is not a package version', () => {
    const result = parseCargoLockFressVersion(coherentFiles()['src-tauri/Cargo.lock']!);
    expect(result).toEqual({ kind: 'ok', value: '1.0.10-beta' });
  });

  it('Cargo.lock: zero fress entries and ambiguous duplicates fail closed', () => {
    const none = parseCargoLockFressVersion('version = 4\n\n[[package]]\nname = "serde"\nversion = "1.0.219"');
    expectErr(none, 'no [[package]] entry with name = "fress"');

    const twice = parseCargoLockFressVersion(
      '[[package]]\nname = "fress"\nversion = "1.0.10-beta"\n\n[[package]]\nname = "fress"\nversion = "1.0.10-beta"'
    );
    expectErr(twice, '2 [[package]] entries named "fress"');
  });

  it('Cargo.lock: quoted array data cannot sever a package record', () => {
    // v3-style inline dependencies array inside the record; the version is
    // read BEFORE dependencies, but this pins that quoted brackets are data.
    const text = [
      '[[package]]',
      'name = "fress"',
      'version = "1.0.10-beta"',
      'dependencies = ["serde 1.0.219", "log 0.4.27"]',
    ].join('\n');
    expect(parseCargoLockFressVersion(text)).toEqual({ kind: 'ok', value: '1.0.10-beta' });
  });
});

describe('version grammar', () => {
  it('strips the optional v-prefix like the app does', () => {
    expect(stripVPrefix('v1.0.10-beta')).toBe('1.0.10-beta');
    expect(stripVPrefix('1.0.10-beta')).toBe('1.0.10-beta');
  });
});

// -- the eight required regression cases --------------------------------------

describe('validateVersions: the required regression matrix', () => {
  it('1. a fully coherent candidate passes', () => {
    const report = validate(coherentFiles());
    expect(report.ok).toBe(true);
    expect(report.canonical).toBe('1.0.10-beta');
    expect(report.checks.filter((c) => c.status === 'fail')).toHaveLength(0);
  });

  it('2. a stale package-lock.json ROOT version fails, naming file, field and observed value', () => {
    const files = coherentFiles();
    const lock = JSON.parse(files['package-lock.json']!);
    lock.version = '1.0.9-beta'; // packages[""] stays bumped: the classic partial `npm install`
    files['package-lock.json'] = JSON.stringify(lock);

    const report = validate(files);
    expect(report.ok).toBe(false);
    expect(failureText(report)).toContain('package-lock.json .version is "1.0.9-beta"');
    expect(failureText(report)).toContain('expected "1.0.10-beta"');
    expect(failureText(report)).toContain('npm install');
  });

  it('3. a stale Cargo.lock fress version fails', () => {
    const files = coherentFiles();
    files['src-tauri/Cargo.lock'] = files['src-tauri/Cargo.lock']!.replace(
      'name = "fress"\nversion = "1.0.10-beta"',
      'name = "fress"\nversion = "1.0.9-beta"'
    );

    const report = validate(files);
    expect(report.ok).toBe(false);
    expect(failureText(report)).toContain('src-tauri/Cargo.lock [[package] name="fress"] version is "1.0.9-beta"');
  });

  it('4. a mismatching tauri.conf.json version fails', () => {
    const files = coherentFiles();
    files['src-tauri/tauri.conf.json'] = JSON.stringify({
      productName: 'Fress',
      version: '1.0.9-beta',
    });

    const report = validate(files);
    expect(report.ok).toBe(false);
    expect(failureText(report)).toContain('src-tauri/tauri.conf.json .version is "1.0.9-beta"');
  });

  it('5. a release tag that differs from the build metadata fails in release mode', () => {
    const report = validate(coherentFiles(), { releaseTag: 'v1.0.9-beta' });
    expect(report.ok).toBe(false);
    expect(failureText(report)).toContain('release tag "v1.0.9-beta" (1.0.9-beta) disagrees with the build version "1.0.10-beta"');
    expect(failureText(report)).toContain('NEVER move or retarget an already-published tag');

    // The same tag without release mode is fine — release mode is opt-in.
    expect(validate(coherentFiles()).ok).toBe(true);
  });

  it('6. a development version newer than the most recent release is accepted when all build metadata agrees', () => {
    // Next-version development state: v1.0.10-beta is the newest PUBLISHED
    // release (per the historical changelog), the tree is already on
    // 1.0.11-beta. This must PASS — the validator never compares the
    // default-branch build version to the latest published release.
    const files = coherentFiles('1.0.11-beta');
    const withChangelog = files as Record<string, string>;
    withChangelog['CHANGELOG.md'] = HISTORICAL_CHANGELOG;

    const report = validateVersions({ files: withChangelog as ValidateInput['files'] });
    expect(report.ok).toBe(true);
    expect(report.canonical).toBe('1.0.11-beta');
  });

  it('7. missing or malformed required fields fail closed with specific diagnostics', () => {
    // package.json without a version field.
    const noPkgVersion = coherentFiles();
    noPkgVersion['package.json'] = JSON.stringify({ name: 'fress' });
    const r1 = validate(noPkgVersion);
    expect(r1.ok).toBe(false);
    expect(failureText(r1)).toContain('package.json .version is missing or is not a string');

    // package-lock.json without the packages[""] entry.
    const noPkgEntry = coherentFiles();
    const lock = JSON.parse(noPkgEntry['package-lock.json']!);
    delete lock.packages[''];
    noPkgEntry['package-lock.json'] = JSON.stringify(lock);
    const r2 = validate(noPkgEntry);
    expect(r2.ok).toBe(false);
    expect(failureText(r2)).toContain('package-lock.json .packages[""].version is missing');

    // Cargo.lock without a fress entry.
    const noFress = coherentFiles();
    noFress['src-tauri/Cargo.lock'] = 'version = 4\n\n[[package]]\nname = "serde"\nversion = "1.0.219"';
    const r3 = validate(noFress);
    expect(r3.ok).toBe(false);
    expect(failureText(r3)).toContain('no [[package]] entry with name = "fress"');

    // Cargo.toml without a [package] version.
    const noCargoVersion = coherentFiles();
    noCargoVersion['src-tauri/Cargo.toml'] = '[package]\nname = "fress"\nedition = "2021"';
    const r4 = validate(noCargoVersion);
    expect(r4.ok).toBe(false);
    expect(failureText(r4)).toContain('src-tauri/Cargo.toml [package] has no "version" key');

    // A required file missing entirely.
    const missingTauri = coherentFiles();
    delete missingTauri['src-tauri/tauri.conf.json'];
    const r5 = validate(missingTauri);
    expect(r5.ok).toBe(false);
    expect(failureText(r5)).toContain('src-tauri/tauri.conf.json is missing');

    // Malformed JSON fails closed (parse error, not a skip).
    const badJson = coherentFiles();
    badJson['src-tauri/tauri.conf.json'] = '{ "productName": truncated';
    const r6 = validate(badJson);
    expect(r6.ok).toBe(false);
    expect(failureText(r6)).toContain('src-tauri/tauri.conf.json is not valid JSON');

    // A present-but-nonsense version value fails closed.
    const nonsense = coherentFiles();
    nonsense['src-tauri/Cargo.toml'] = '[package]\nname = "fress"\nversion = "banana"';
    const r7 = validate(nonsense);
    expect(r7.ok).toBe(false);
    expect(failureText(r7)).toContain('not a valid project version');

    // Unreadable file (exists but I/O error) fails closed.
    const r8 = validate(coherentFiles(), { readErrors: { 'package.json': 'EACCES: permission denied' } });
    expect(r8.ok).toBe(false);
    expect(failureText(r8)).toContain('package.json could not be read (EACCES: permission denied)');
  });

  it('8. historical versions in changelog entries cause no false positives', () => {
    // The changelog is NOT an authoritative input: the validator never reads
    // it. A changelog full of past versions next to a coherent candidate
    // passes (case 6 also pins the trailing-changelog direction).
    const files = coherentFiles() as Record<string, string>;
    files['CHANGELOG.md'] = HISTORICAL_CHANGELOG;
    const report = validateVersions({ files: files as ValidateInput['files'] });
    expect(report.ok).toBe(true);
    expect(report.checks.some((c) => c.file === 'CHANGELOG.md')).toBe(false);
  });
});

// -- release-tag and equality semantics ----------------------------------------

describe('validateVersions: release-tag semantics', () => {
  it('a v-prefixed tag equals the bare manifest version', () => {
    const report = validate(coherentFiles(), { releaseTag: 'v1.0.10-beta' });
    expect(report.ok).toBe(true);
    expect(report.releaseTag).toEqual({ input: 'v1.0.10-beta', normalized: '1.0.10-beta' });
  });

  it('an unparsable release tag fails instead of being interpreted as "some version"', () => {
    for (const bad of ['v1.0.10junk', 'beta-build', 'v01.2.3', '1.0.10-beta..2']) {
      const report = validate(coherentFiles(), { releaseTag: bad });
      expect(report.ok).toBe(false);
      expect(failureText(report)).toContain(`--release-tag "${bad}" is not a valid project version tag`);
    }
  });

  it('an empty release-tag argument is ignored (default-branch mode)', () => {
    expect(validate(coherentFiles(), { releaseTag: '' }).ok).toBe(true);
  });
});

// -- disk loading + the real npm script -----------------------------------------

describe('loadVersionFiles + the real npm script', () => {
  const scratchRoots: string[] = [];

  afterAll(() => {
    for (const root of scratchRoots) rmSync(root, { recursive: true, force: true });
  });

  function makeFixtureRoot(version: string, mutate?: (root: string) => void): string {
    const root = mkdtempSync(join(resolve(process.cwd()), 'node_modules', '.tmp-version-fixture-'));
    scratchRoots.push(root);
    for (const [rel, content] of Object.entries(coherentFiles(version))) {
      const abs = join(root, rel);
      mkdirSync(abs.slice(0, abs.lastIndexOf('/')), { recursive: true });
      writeFileSync(abs, content!);
    }
    writeFileSync(join(root, 'CHANGELOG.md'), HISTORICAL_CHANGELOG);
    mutate?.(root);
    return root;
  }

  it('loadVersionFiles reads a coherent checkout and reports missing files as missing (not skipped)', () => {
    const root = makeFixtureRoot('1.0.10-beta');
    const loaded = loadVersionFiles(root);
    expect(loaded.missing).toHaveLength(0);
    expect(Object.keys(loaded.readErrors)).toHaveLength(0);

    rmSync(join(root, 'src-tauri/tauri.conf.json'));
    const after = loadVersionFiles(root);
    expect(after.missing).toEqual(['src-tauri/tauri.conf.json']);
  });

  it('the real npm script exits 0 on a coherent fixture and 1 on drift', () => {
    const good = makeFixtureRoot('1.0.10-beta');
    const goodRun = spawnSync('npm', ['run', '--silent', 'validate:versions', '--', '--root', good], {
      cwd: resolve(process.cwd()),
      encoding: 'utf8',
      timeout: 120_000,
    });
    expect(goodRun.status).toBe(0);
    expect(goodRun.stdout).toContain('validate:versions PASSED');

    const drifted = makeFixtureRoot('1.0.10-beta', (root) => {
      // Stale lockfile: the exact drift class this guard exists for.
      const lockPath = join(root, 'package-lock.json');
      const lock = JSON.parse(readFileSync(lockPath, 'utf8'));
      lock.packages[''].version = '1.0.9-beta';
      writeFileSync(lockPath, JSON.stringify(lock, null, 2));
    });
    const badRun = spawnSync('npm', ['run', '--silent', 'validate:versions', '--', '--root', drifted], {
      cwd: resolve(process.cwd()),
      encoding: 'utf8',
      timeout: 120_000,
    });
    expect(badRun.status).toBe(1);
    expect(badRun.stdout).toContain('validate:versions FAILED');
    expect(badRun.stdout).toContain('package-lock.json .packages[""].version is "1.0.9-beta"');
  });

  it('the real npm script enforces release-tag mode end to end', () => {
    const root = makeFixtureRoot('1.0.10-beta');
    const mismatch = spawnSync(
      'npm',
      ['run', '--silent', 'validate:versions', '--', '--root', root, '--release-tag', 'v1.0.9-beta'],
      { cwd: resolve(process.cwd()), encoding: 'utf8', timeout: 120_000 }
    );
    expect(mismatch.status).toBe(1);
    expect(mismatch.stdout).toContain('disagrees with the build version');

    const match = spawnSync(
      'npm',
      ['run', '--silent', 'validate:versions', '--', '--root', root, '--release-tag', 'v1.0.10-beta'],
      { cwd: resolve(process.cwd()), encoding: 'utf8', timeout: 120_000 }
    );
    expect(match.status).toBe(0);
  });

  it('unknown CLI arguments exit 2 with usage', () => {
    const run = spawnSync('npm', ['run', '--silent', 'validate:versions', '--', '--nonsense'], {
      cwd: resolve(process.cwd()),
      encoding: 'utf8',
      timeout: 120_000,
    });
    expect(run.status).toBe(2);
    expect(run.stderr).toContain('unknown argument');
  });
});
