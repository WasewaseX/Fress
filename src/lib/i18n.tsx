/**
 * Translation coverage guard: an unexpected runtime key falls back to the
 * English string (the UI must never render a raw key), but ONLY silently in
 * production. In development and tests the fallback warns once per key so a
 * forgotten translation shows up immediately instead of hiding as debt that
 * only the dictionary-parity CI test catches later.
 */
const warnedMissing = new Set<string>();
function isDevOrTest(): boolean {
  try {
    // vitest sets VITEST; vite dev sets DEV. Both live on import.meta.env.
    const env = (import.meta as unknown as { env?: { DEV?: boolean; VITEST?: string } }).env;
    return Boolean(env?.DEV || env?.VITEST);
  } catch {
    return false;
  }
}

export function isRtl(lang: Language): boolean {
  return lang === 'fa';
}

interface I18nContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
  rtl: boolean;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && saved in DICTS) return saved as Language;
    } catch {
      // ignore
    }
    return 'en';
  });

  const rtl = isRtl(lang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  }, [lang, rtl]);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // ignore
    }
  }, []);

  const t = useCallback(
    (key: string): string => {
      const dict = DICTS[lang];
      const hit = dict[key];
      if (hit !== undefined) return hit;
      const fallback = en[key];
      if (fallback !== undefined) {
        if (isDevOrTest() && !warnedMissing.has(`${lang}:${key}`)) {
          warnedMissing.add(`${lang}:${key}`);
          // Visible in the console, silent in the UI: a translated surface
          // is showing English. The parity test fails CI for keys that exist
          // in the source; this warning covers keys assembled at runtime.
          console.warn(
            `[i18n] "${lang}" has no translation for "${key}" - using the English fallback. Add the key to every dictionary.`
          );
        }
        return fallback;
      }
      return key;
    },
    [lang]
  );

  return <I18nContext.Provider value={{ lang, setLang, t, rtl }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
