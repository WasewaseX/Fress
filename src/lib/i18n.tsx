const DICTS: Record<Language, Dict> = { en, fa, es, fr, de };

// Out-of-component translation: module code that is not a React component
// (download helpers, toasts fired from plain functions) still needs the
// active language. The provider keeps this fresh on every render.
let activeLang: Language = 'en';
export function translate(key: string): string {
  const dict = DICTS[activeLang];
  return dict[key] ?? en[key] ?? key;
}

export function isRtl(lang: Language): boolean {
  return lang === 'fa';
}

/** Maps a Category enum value to its translation key. */
export function categoryKey(cat: string): string {
  switch (cat) {
    case 'All': return 'category.all';
    case 'Productivity & Office': return 'category.productivity';
    case 'Developer & Code': return 'category.developer';
    case 'Design & Creative': return 'category.design';
    case 'Utilities & System': return 'category.utilities';
    case 'Privacy & Security': return 'category.privacy';
    case 'Media, Audio & Video': return 'category.media';
    case 'AI & Knowledge': return 'category.ai';
    default: return 'category.all';
  }
}

interface I18nContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
  rtl: boolean;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && saved in DICTS) return saved as Language;
    } catch {
      // ignore
    }
    return 'en';
  });

  const rtl = isRtl(lang);
  activeLang = lang;

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  }, [lang, rtl]);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // ignore
    }
  }, []);

  const t = useCallback(
    (key: string): string => {
      const dict = DICTS[lang];
      return dict[key] ?? en[key] ?? key;
    },
    [lang]
  );

  return <I18nContext.Provider value={{ lang, setLang, t, rtl }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
